-- Durable order intent and state transitions for paper/shadow execution only.
CREATE TABLE IF NOT EXISTS paper_orders (
    id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    config_id                BIGINT UNSIGNED NOT NULL,
    symbol                   VARCHAR(30) NOT NULL,
    market                   VARCHAR(10) NOT NULL,
    timeframe                VARCHAR(10) NOT NULL,
    strategy_name            VARCHAR(100) NOT NULL,
    signal_open_time         BIGINT NOT NULL,
    entry_time               BIGINT NOT NULL,
    direction                ENUM('LONG','SHORT') NOT NULL,
    requested_entry_price    DECIMAL(24,10) NOT NULL,
    stop_loss                DECIMAL(24,10) NOT NULL,
    take_profit              DECIMAL(24,10) NOT NULL,
    atr_at_signal            DECIMAL(24,10) NOT NULL,
    ml_model_id              VARCHAR(100) NULL,
    ml_probability           DECIMAL(9,8) NULL,
    status                   ENUM('PENDING','FILLED','EXPIRED','CANCELLED','REJECTED') NOT NULL DEFAULT 'PENDING',
    state_reason             VARCHAR(500) NULL,
    fill_price               DECIMAL(24,10) NULL,
    position_id              BIGINT UNSIGNED NULL,
    state_changed_by_user_id BIGINT UNSIGNED NULL,
    created_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    filled_at                TIMESTAMP NULL DEFAULT NULL,
    terminal_at              TIMESTAMP NULL DEFAULT NULL,
    UNIQUE KEY uq_paper_orders_signal (config_id, signal_open_time),
    INDEX idx_paper_orders_pending (status, entry_time),
    INDEX idx_paper_orders_history (config_id, created_at),
    INDEX idx_paper_orders_position (position_id)
) ENGINE=InnoDB;
