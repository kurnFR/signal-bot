"""AI strategy provider fallback contracts; all provider calls are mocked."""
import json
from unittest.mock import Mock

from web.routes import custom_strategy


def test_generate_ai_falls_back_from_primary_provider_to_openrouter(monkeypatch):
    monkeypatch.setattr(custom_strategy, "LLM_PROVIDER", "9router")
    monkeypatch.setattr(custom_strategy, "NINEROUTER_BASE_URL", "https://primary.example/v1")
    monkeypatch.setattr(custom_strategy, "NINEROUTER_API_KEY", "primary-test-key")
    monkeypatch.setattr(custom_strategy, "NINEROUTER_MODEL", "primary/model")
    monkeypatch.setattr(custom_strategy, "OPENROUTER_API_KEY", "fallback-test-key")
    monkeypatch.setattr(custom_strategy, "OPENROUTER_BASE_URL", "https://fallback.example/v1")
    monkeypatch.setattr(custom_strategy, "OPENROUTER_MODEL", "fallback/model")
    monkeypatch.setattr(custom_strategy, "ANTHROPIC_API_KEY", "anthropic-test-key")

    response = json.dumps({
        "name": "fallback_strategy_v1",
        "displayName": "Fallback Strategy",
        "longConditions": [{"indicator": "rsi", "operator": "<", "value": 28}],
        "shortConditions": [{"indicator": "rsi", "operator": ">", "value": 72}],
        "slAtrMult": 2,
        "riskRewardRatio": 3,
        "chatResponse": "Generated by fallback provider.",
    })
    provider_call = Mock(side_effect=[None, response])
    anthropic_call = Mock()
    monkeypatch.setattr(custom_strategy, "_call_openai_compatible_api", provider_call)
    monkeypatch.setattr(custom_strategy, "_call_anthropic_api", anthropic_call)

    result = custom_strategy.generate_ai_strategy(
        custom_strategy.GenerateAIStrategyRequest(prompt="Create an RSI reversal strategy")
    )

    assert result["status"] == "success"
    assert result["provider"] == "OpenRouter (model)"
    assert result["strategy"]["name"] == "fallback_strategy_v1"
    assert result["strategy"]["longConditions"] == [
        {"indicator": "rsi", "operator": "<", "value": 28.0}
    ]
    assert result["chatResponse"] == "Generated by fallback provider."
    assert provider_call.call_count == 2
    assert provider_call.call_args_list[0].kwargs["url"] == "https://primary.example/v1/chat/completions"
    assert provider_call.call_args_list[1].kwargs["url"] == "https://fallback.example/v1/chat/completions"
    assert not anthropic_call.called


def test_generate_ai_uses_heuristic_when_configured_providers_fail(monkeypatch):
    monkeypatch.setattr(custom_strategy, "LLM_PROVIDER", "9router")
    monkeypatch.setattr(custom_strategy, "NINEROUTER_BASE_URL", "https://primary.example/v1")
    monkeypatch.setattr(custom_strategy, "NINEROUTER_API_KEY", "primary-test-key")
    monkeypatch.setattr(custom_strategy, "NINEROUTER_MODEL", "primary/model")
    monkeypatch.setattr(custom_strategy, "OPENROUTER_API_KEY", "")
    monkeypatch.setattr(custom_strategy, "ANTHROPIC_API_KEY", "")

    provider_call = Mock(return_value=None)
    monkeypatch.setattr(custom_strategy, "_call_openai_compatible_api", provider_call)

    result = custom_strategy.generate_ai_strategy(
        custom_strategy.GenerateAIStrategyRequest(
            prompt="Create a strategy that buys when RSI is below 30 and volume is strong"
        )
    )

    assert result["status"] == "success"
    assert result["provider"] == "AI Quantitative Heuristic Engine"
    assert result["strategy"]["name"]
    assert result["strategy"]["longConditions"]
    provider_call.assert_called_once()
